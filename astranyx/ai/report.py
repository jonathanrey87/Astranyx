"""Export AI-assisted investigation results without changing finding schema v1."""

from __future__ import annotations

import json
from datetime import UTC, datetime
from html import escape
from pathlib import Path
from typing import Any


def build_ai_report(context: dict[str, Any]) -> dict[str, Any]:
    """Build a companion report from an executed investigation context."""
    investigations = context.get("ai_investigations", [])
    errors = context.get("ai_investigation_errors", [])

    if not isinstance(investigations, list):
        raise TypeError("ai_investigations must be a list")
    if not isinstance(errors, list):
        raise TypeError("ai_investigation_errors must be a list")

    entries = []
    for item in investigations:
        if not isinstance(item, dict):
            raise TypeError("AI investigation entries must be dictionaries")

        entries.append(
            {
                "finding_fingerprint": str(item.get("finding_fingerprint", "")),
                "summary": str(item.get("summary", "")),
                "impact": str(item.get("impact", "")),
                "next_step": str(item.get("next_step", "")),
                "ai_verified": False,
                "requires_validation": True,
            }
        )

    return {
        "report_type": "astranyx_ai_investigation",
        "schema_version": 1,
        "generated": datetime.now(UTC).isoformat(),
        "verification_status": "unverified",
        "investigations": entries,
        "errors": [
            {
                "index": error.get("index"),
                "type": str(error.get("type", "unknown")),
            }
            for error in errors
            if isinstance(error, dict)
        ],
    }


def write_ai_json(report: dict[str, Any], path: str | Path) -> Path:
    """Write the AI companion report as UTF-8 JSON."""
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return output


def write_ai_html(report: dict[str, Any], path: str | Path) -> Path:
    """Write a standalone HTML report with escaped untrusted content."""
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)

    sections = []

    for item in report.get("investigations", []):
        fingerprint = escape(str(item.get("finding_fingerprint", "")))
        summary = escape(str(item.get("summary", "")))
        impact = escape(str(item.get("impact", "")))
        next_step = escape(str(item.get("next_step", "")))

        sections.append(f"""
        <article class="finding">
            <div class="label">AI ANALYSIS · UNVERIFIED</div>
            <h2>{fingerprint}</h2>
            <h3>Summary</h3>
            <p>{summary}</p>
            <h3>Potential impact</h3>
            <p>{impact}</p>
            <h3>Recommended validation</h3>
            <p>{next_step}</p>
        </article>
        """)

    content = "\n".join(sections) or ("<p>No AI investigations are available.</p>")

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Astranyx | AI Investigation</title>
<style>
:root {{
    color-scheme: dark;
    font-family: system-ui, sans-serif;
}}
body {{
    margin: 0;
    background: #071525;
    color: #e8f4ff;
}}
main {{
    max-width: 1000px;
    margin: 50px auto;
    padding: 24px;
}}
h1 {{
    color: #4dc9ff;
}}
.subtitle {{
    color: #9eb6cb;
}}
.finding {{
    background: #102b45;
    border: 1px solid #245c80;
    border-radius: 14px;
    padding: 28px;
    margin-top: 24px;
}}
.label {{
    color: #ffc66d;
    font-weight: 700;
    font-size: 12px;
    letter-spacing: 1px;
}}
h2 {{
    overflow-wrap: anywhere;
}}
h3 {{
    color: #6bd5ff;
}}
p {{
    line-height: 1.6;
    overflow-wrap: anywhere;
    white-space: pre-wrap;
}}
footer {{
    margin-top: 40px;
    color: #9eb6cb;
}}
</style>
</head>
<body>
<main>
<h1>ASTRANYX</h1>
<p class="subtitle">Digital Evidence Decoded | AI Investigation</p>
<p>AI-generated explanations are unverified and require independent validation.</p>
{content}
<footer>Generated by Astranyx. AI analysis is not proof of exploitation.</footer>
</main>
</body>
</html>
"""

    output.write_text(html, encoding="utf-8")
    return output
